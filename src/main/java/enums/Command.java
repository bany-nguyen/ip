package enums;

/** Lists command names supported by the task application. */
public enum Command {
    /** Creates a to-do task. */
    TODO,
    /** Creates a deadline task. */
    DEADLINE,
    /** Creates an event task. */
    EVENT,
    /** Ends the Bany session. */
    BYE,
    /** Marks a task as done. */
    MARK,
    /** Marks a task as not done. */
    UNMARK,
    /** Deletes a task. */
    DELETE,
    /** Displays all tasks. */
    LIST



}
